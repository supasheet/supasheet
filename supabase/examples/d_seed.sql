-- Desk Seeder
-- ================================================================
-- Demo data for the desk (customer support / helpdesk) module.
-- Apply supabase/examples/20251005100000_desk.sql first:
--
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 \
--     -f supabase/examples/20251005100000_desk.sql \
--     -f supabase/examples/d_seed.sql
--
-- Volume: 5 teams, 5 SLA policies, 12 agents, 14 customer accounts,
-- 22 contacts, 14 categories, 6 known problems, 60 tickets spread
-- over the last seven months, 80 replies and internal notes, 55
-- worklogs, 26 CSAT responses, 16 knowledge base articles and 12
-- canned responses.
--
-- Dates are all relative to `current_date` / `current_timestamp`, so
-- the dashboards, the 14-day line chart, the 8-week area chart and
-- the monthly rollup all have shape whenever this is run.
--
-- Four hardcoded users are seeded first so this file can run
-- independently of supabase/seed.sql (`on conflict do nothing`, so it
-- is also safe to run after supabase/seed.sql has created the first
-- three):
--   b73eb03e-fb7a-424d-84ff-18e2791ce0b8  superadmin@supasheet.app (x-admin)
--   b73eb03e-fb7a-424d-84ff-18e2791ce0b7  agent@supasheet.app      (agent)
--   b73eb03e-fb7a-424d-84ff-18e2791ce0b1  user1@supasheet.app      (user)
--   b73eb03e-fb7a-424d-84ff-18e2791ce0b4  user@supasheet.app       (user)
--
-- Sign in as agent@supasheet.app to see the desk from a support
-- agent's seat, and as user@supasheet.app to see the requester view
-- (only their own tickets, only public replies, only published
-- articles — all enforced by RLS).
--
-- Password for every seeded user: the shared bcrypt hash below,
-- matching the rest of the Supasheet examples.
--
-- Not idempotent beyond the auth rows: re-running inserts duplicate
-- primary keys. Run `npx supabase db reset` to start over.
-- ================================================================
